// Imports every language GitHub recognizes, from GitHub Linguist's languages.yml, into
// data/github/languages.yaml. Each one gets a page on langwhy, so whatever GitHub shows on a repo
// can be looked up. `node scripts/import-github.mjs [tag]`; the default tag is pinned below.
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse, stringify } from "yaml";

const tag = process.argv[2] ?? "v9.7.0";
const url = `https://raw.githubusercontent.com/github-linguist/linguist/${tag}/lib/linguist/languages.yml`;
const res = await fetch(url);
if (!res.ok) throw new Error(`${url}: ${res.status}`);
const linguist = parse(await res.text());

// "C++" -> "cpp", "F#" -> "fsharp", "Objective-C++" -> "objective-cpp", "Ren'Py" -> "renpy".
const slug = (name) => name.toLowerCase()
  .replace(/\+\+/g, "pp").replace(/\+/g, "plus").replace(/#/g, "sharp").replace(/\*/g, "star").replace(/'/g, "")
  .normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const seen = new Map();
const languages = Object.entries(linguist).map(([name, l]) => {
  const id = slug(name);
  if (!id || seen.has(id)) throw new Error(`slug "${id}" of "${name}" is empty or also used by "${seen.get(id)}"`);
  seen.set(id, name);
  const entry = { name, id, type: l.type };
  if (l.group) entry.group = l.group;
  if (l.aliases?.length) entry.aliases = l.aliases;
  if (l.extensions?.length) entry.extensions = l.extensions;
  if (l.filenames?.length) entry.filenames = l.filenames;
  return entry;
});

const header = `# Generated by scripts/import-github.mjs from GitHub Linguist ${tag} (MIT), do not edit by hand.
# ${url}
# Every language GitHub can put on a repository. A language with a card links to it by name
# (or by the card's \`github\` field); the others get a short page built from these facts.
`;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "data", "github", "languages.yaml");
writeFileSync(out, header + stringify({ linguist: tag, languages }, { lineWidth: 0 }));
console.log(`${languages.length} languages from Linguist ${tag} -> data/github/languages.yaml`);
