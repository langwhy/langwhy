// 8x8 pixel icons, one per language type, rendered as crisp inline SVG. '#' is a filled pixel.
const GLYPHS: Record<string, string[]> = {
  systems:    [".#.##.#.", "########", "#.####.#", "##.##.##", "##.##.##", "#.####.#", "########", ".#.##.#."],
  web:        ["..####..", ".#.##.#.", "#..##..#", "########", "########", "#..##..#", ".#.##.#.", "..####.."],
  backend:    ["########", "#.....##", "########", "#.....##", "########", "#.....##", "########", "........"],
  scripting:  [".#####..", ".#...##.", ".#...###", ".#.....#", ".#.###.#", ".#.....#", ".#.###.#", ".#######"],
  data:       ["........", "......##", "......##", "...##.##", "...##.##", "##.##.##", "##.##.##", "########"],
  mobile:     [".######.", ".#....#.", ".#....#.", ".#....#.", ".#....#.", ".#....#.", ".#.##.#.", ".######."],
  functional: ["##......", ".##.....", "..##....", "..###...", ".##.##..", ".#...##.", "##....##", "........"],
  query:      ["########", "#..#...#", "########", "#..#...#", "#..#...#", "########", "#..#...#", "########"],
  shell:      ["........", "#.......", ".#......", "..#.....", ".#......", "#.......", "...#####", "........"],
  config:     ["..#..#..", ".######.", "###..###", ".#....#.", ".#....#.", "###..###", ".######.", "..#..#.."],
  embedded:   ["#.#.#.#.", "########", "#......#", "#.##...#", "#.##...#", "#......#", "########", ".#.#.#.#"],
  games:      ["........", ".######.", "##.##.##", "#.####.#", "#.#..#.#", "##.##.##", ".######.", "........"],
  academic:   ["...##...", ".######.", "########", ".######.", "...#....", "..###...", ".#...#..", "........"],
  logo:       [".#####..", "##...##.", ".....##.", "....##..", "...##...", "...##...", "........", "...##..."],
};

export function icon(name: string, size = 16, label?: string): string {
  const rows = GLYPHS[name] ?? GLYPHS.logo;
  const rects = rows.flatMap((row, y) =>
    [...row].map((c, x) => (c === "#" ? `<rect x="${x}" y="${y}" width="1" height="1"/>` : "")),
  ).join("");
  const a11y = label ? `role="img" aria-label="${label}"` : `aria-hidden="true"`;
  return `<svg class="px" width="${size}" height="${size}" viewBox="0 0 8 8" shape-rendering="crispEdges" fill="currentColor" ${a11y}>${rects}</svg>`;
}
